SKIP_DIRS = {".git", "node_modules", "dist", ".playwright-mcp", "bin", "obj", "temp", ".agnes", ".kilo", ".workbuddy-ai", ".workbuddy"}
SKIP_EXT = {".png", ".jpg", ".jpeg", ".doc", ".docx", ".xls", ".xlsx", ".pdf", ".webm", ".woff", ".woff2", ".ttf"}
EXTRA_FILES = ["AGENTS.md", "项目全局规则.md", "README.md"]
# 历史记录类文档：其旧路径是「当时发生的事实」，改写会破坏准确性
SKIP_REL_PREFIX = ("docs/90-归档/",)
SKIP_REL_EXACT = {
    "docs/40-实施/分类清单-2026-09-28.md",          # 2026-09-28 迁移执行清单
    "docs/00-工程体系/文档失效评估与归档方案-V1.md",  # 2026-09-24 失效评估记录
    "docs/00-工程体系/文档过期清理审计报告-V1.md",    # 本轮审计记录（含归档路径）
    "docs/10-YZH架构/99-文档来源索引-V1.md",         # 明确声明「路径为历史凭证」
}

changed = {}
for dirpath, dirnames, filenames in os.walk(ROOT):
    dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS]
    for fn in filenames:
        if os.path.splitext(fn)[1].lower() in SKIP_EXT:
            continue
        fp = os.path.join(dirpath, fn)
        rel = os.path.relpath(fp, ROOT)
        # 只改 docs/ 与三个根权威文件；⛔ 不碰 src/（含禁止修改的 src/old/）
        if not (rel.startswith("docs" + os.sep) or rel in EXTRA_FILES):
            continue
        if not (fn.endswith(".md") or rel in EXTRA_FILES):
            continue
        if rel.startswith(SKIP_REL_PREFIX) or rel in SKIP_REL_EXACT:
            continue
        try:
            with open(fp, encoding="utf-8") as fh:
                text = fh.read()
        except (UnicodeDecodeError, OSError):
            continue
        orig = text
        hits = 0
        for old, new in REPL:
            if old and old in text:
                hits += text.count(old)
                text = text.replace(old, new)
        if text != orig:
            changed[rel] = hits
            if APPLY:
                with open(fp, "w", encoding="utf-8") as fh:
                    fh.write(text)

print(f"{'APPLIED' if APPLY else 'DRY-RUN'}  改动文件数: {len(changed)}  替换次数: {sum(changed.values())}\n")
for rel in sorted(changed, key=lambda k: -changed[k]):
    print(f"  {changed[rel]:4d}  {rel}")
