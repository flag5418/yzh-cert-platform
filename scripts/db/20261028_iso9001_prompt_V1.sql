## 通用属性说明

**docCategory 分类规则：**
- 生产类：工艺卡、作业指导书、工序记录等
- 运营类：合同管理、客户沟通、订单评审等
- 管理类：手册、程序文件、管理制度等
- 内审类：审核计划、审核报告、不符合项报告等
- 资质类：营业执照、认证证书、许可证等
- 设备类：设备台账、维护保养记录、操作规程等
- 设计类：设计图纸、设计输入输出、评审记录等
- 监测类：检验记录、检测报告、校准证书等
- 其他类：不属于以上类别的文档

