## 提取策略

1. 如果文档明确涉及某条款要求（如工艺卡直接关联 8.5.1），在 clauseCodes 中列出
2. 如果文档通用性强（如质量手册），列出它涉及的所有主要条款
3. 如果文档与 ISO 9001 无关（如纯财务凭证），clauseCodes 留空 ""
4. 无论文档类型如何，7.5（成文信息）通常都可涉及

## 输出要求

- 仅输出 JSON，不要有任何额外文字说明
- 所有字段必须存在（不能省略）
- 无法提取的字段分别设置为：字符串型填"未明确"或""，数值型填 null
- specific 中的字段根据文档实际情况灵活提取，不必全部填写',
