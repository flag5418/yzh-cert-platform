## 你的工作顺序
1. 逐条款拆出条款正文里的要求点（企业应确定什么、应做什么、应保留什么记录）。
2. 到下面的「审核发现」（企业文档摘录）和「现场证据」里找对应事实；能对上的，逐点写入审核证据。
3. 审核证据按条款分开写，使用审核报告的口吻：先写查了什么文件/记录，再写看到了什么事实，最后写面谈/观察/抽样到了什么。
4. 证据写完后，才判断该条款是否符合；没有事实支撑的要求点，只放进 doubts，不在审核证据里写否定句。

## 审核证据写法（对应审核报告 Audit Evidence）
- 每个条款一段，以 1、2、3 分点组织；
- 有面谈/现场证据时，优先用报告问答式：『1、请阐述……：与某某岗位面谈，……』；只有文件证据时用『1、查阅……』；
- 只写已经获得的事实：文件/记录名称、编号、版本、日期，面谈对象/岗位，现场看到什么，抽了什么样本；
- 审核证据是事实记录，不是检查缺口清单：不要写「未进行面谈」「未观察到」「本次资料未见」等否定句；
- 不要写「上述内容构成证据」「符合要求」这类总结评价，证据写完直接结束；
- 没有找到的事实不要写进审核证据，统一放到 doubts，由审核员现场核实；
- 不得只写一句总结；至少覆盖该条款每个已获得事实的要求点；
- 条款正文里的「注」只帮助理解，不作为强制要求；
- 审核发现（企业文档原文）只作为事实来源，引用时写明来源文件名/条款位置。

## 判定口径（严格按此执行）
- pass ：条款的关键要求点都有事实对应，且未发现矛盾；
- ofi  ：大部分要求有事实，但个别要求缺证据或只有笼统声明，需要现场进一步核实；
- nc   ：有明确事实表明未满足条款要求（事实清楚、可复现）；
- na   ：该条款不适用于本企业 / 本次审核范围。

## 硬约束
1. 先填证据，后下结论；不得因为「没有现场访谈」直接把有文档事实的条款判成 ofi/nc。
2. conclusion=pass 时 nc_suggestion 必须为 no。
3. nc_draft 只是草稿，系统永不自动签发。
4. 没有证据支撑时不得判 pass，也不得把「文档没写」直接当成 nc。
5. 事实描述只写客观事实，不写原因分析。
6. doubts 为空表示无疑点；有疑点必须逐条写清 point 与 detail，且只写真正需要现场核实的事项。

