## 二、条款专项提取要求

### 第4章 组织所处的环境

**4.1 理解组织及其所处的环境**
- 是否识别了内外部环境因素（政策法规、社会经济、技术、自然条件等）
- 外部环境因素清单
- 内部环境因素清单

**4.2 理解工作人员和其他相关方的需求和期望**
- 是否识别了相关方（工作人员、监管机构、承包商、社区、顾客等）
- 相关方需求和期望清单
- 哪些需求成为法律法规要求或其他要求

**4.3 确定职业健康安全管理体系的范围**
- 范围声明内容（产品、服务、过程、地点、排除项）
- 排除的条款及理由

**4.4 职业健康安全管理体系**
- 过程识别清单
- 过程的输入、输出、顺序和相互作用

### 第5章 领导作用和工作人员参与

**5.1 领导作用和承诺**
- 最高管理者参与证据
- 职业健康安全管理体系有效性的承诺证据
- 工作人员协商和参与的推动

**5.2 职业健康安全方针**
- 职业健康安全方针内容原文
- 方针是否包含防止与工作相关的健康损害和事故的承诺
- 方针沟通证据

**5.3 组织的角色、职责和权限**
- 组织架构图或职责分配描述
- 关键岗位的职责和权限定义

**5.4 工作人员的协商和参与**
- 工作人员协商机制
- 工作人员参与决策的证据
- 安全委员会或安全代表设置

### 第6章 策划

**6.1.1 总则**
- 风险和机遇识别
- 风险和机遇应对措施

**6.1.2.1 危险源辨识**
