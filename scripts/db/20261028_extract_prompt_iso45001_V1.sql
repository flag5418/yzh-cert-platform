## 三、输出要求

1. 仅输出 JSON，不要有任何额外文字说明
2. 所有字段必须存在（不能省略），无法提取的字段设置为：字符串型填"未明确"或""，数组型填 []，对象型填 {}
3. 条款专项信息按以下格式组织：
```json
{
  "clauseDetails": {
    "4.1": { "applicable": true/false, "evidence": "证据描述", "extractedInfo": { ... } },
    "4.2": { "applicable": true/false, "evidence": "证据描述", "extractedInfo": { ... } },
    ...
  }
}
```
4. 对于不适用的条款，applicable 设为 false，evidence 和 extractedInfo 留空
5. 对于适用的条款，applicable 设为 true，evidence 描述文档中体现该条款要求的具体内容，extractedInfo 提取该条款要求的专项信息
6. 所有日期格式统一为 YYYY-MM-DD 或 YYYY-MM
7. 人员姓名、产品名称等实体名称必须与文档原文一致
8. 条款编号使用标准编号格式（如 4.1、5.4、6.1.2.1、8.1.2 等）

## 四、提取策略

1. 先通读全文，判断文档类型和涉及的主要安全管理过程
2. 提取通用字段（keyPersons、keyDates、keyProducts、keyMeasures、tableData）
3. 逐条款判断适用性，提取条款专项信息
4. 对于危险源辨识清单类文档，重点提取 6.1.2.1 的专项信息
5. 对于风险评价类文档，重点提取 6.1.2.2 的专项信息
6. 对于应急预案类文档，重点提取 8.2 的专项信息
7. 对于事故调查类文档，重点提取 10.2 的专项信息
8. 对于内审资料，重点提取 9.2 的专项信息
9. 对于管理评审资料，重点提取 9.3 的专项信息
10. 对于职业体检报告，重点提取 9.1.1 的专项信息'
