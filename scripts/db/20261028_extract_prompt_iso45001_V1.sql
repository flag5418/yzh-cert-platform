- 风险等级划分
- 不可接受风险清单

**6.1.2.3 职业健康安全机遇评价**
- 机遇识别清单
- 机遇利用措施

**6.1.3 法律法规要求和其他要求的确定**
- 法律法规要求清单
- 其他要求清单（行业标准、协议等）
- 法律法规获取和更新机制

**6.1.4 措施的策划**
