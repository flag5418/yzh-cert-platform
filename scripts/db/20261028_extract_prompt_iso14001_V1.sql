## 二、条款专项提取要求

### 第4章 组织所处的环境

**4.1 理解组织及其所处的环境**
- 是否识别了内外部环境因素（政策法规、市场技术、文化、自然环境等）
- 外部环境因素清单
- 内部环境因素清单
- 这些因素是否被监视和评审

**4.2 理解相关方的需求和期望**
- 是否识别了相关方（监管机构、社区、员工、顾客、供应商、NGO等）
- 相关方需求和期望清单
- 哪些需求成为合规义务

**4.3 确定环境管理体系的范围**
- 范围声明内容（产品、服务、过程、地点、排除项）
- 排除的条款及理由

**4.4 环境管理体系**
- 过程识别清单
- 过程的输入、输出、顺序和相互作用

### 第5章 领导作用

**5.1 领导作用与承诺**
- 最高管理者参与证据
- 环境管理体系有效性的承诺证据
- 环境方针的推动

**5.2 环境方针**
- 环境方针内容原文
- 方针是否与组织宗旨和战略方向一致
- 方针是否包含保护环境、污染预防、持续改进的承诺
- 方针沟通证据

**5.3 组织的角色、职责和权限**
- 组织架构图或职责分配描述
- 关键岗位的职责和权限定义
- 环境管理体系代表任命

### 第6章 策划

**6.1.1 总则**
- 风险和机遇识别
- 风险和机遇应对措施

**6.1.2 环境因素**
- 环境因素识别清单（大气排放、水体排放、固废、噪声、资源消耗、能源使用等）
- 重要环境因素评价准则
- 重要环境因素清单
- 环境因素更新机制

**6.1.3 合规义务**
- 合规义务清单（法律法规、许可证要求、行业标准、协议等）
- 合规义务的获取和更新机制
- 合规义务在体系中的应用

**6.1.4 措施的策划**
- 环境因素管理措施
- 合规义务履行措施
- 风险和机遇应对措施

**6.2.1 环境目标**
- 环境目标清单（公司级、部门级、项目级）
- 目标是否可测量、与环境方针一致

**6.2.2 实现环境目标的措施的策划**
- 目标实现措施和责任人
- 目标完成情况的监视

### 第7章 支持

**7.1 资源**
- 资源配置原则和决策依据
- 环保设施和设备清单

**7.2 能力**
- 岗位能力要求
- 培训需求识别和培训计划
- 培训实施记录和效果评价

**7.3 意识**
- 员工环境意识培训记录
- 方针和目标的理解证据
- 不符合项后果的认知

**7.4.1 总则**
- 信息交流管理程序

**7.4.2 内部信息交流**
- 内部环境信息交流（会议、通知、报告）

**7.4.3 外部信息交流**
- 外部信息交流（监管机构、社区、顾客）
- 外部信息交流决策

**7.5 文件化信息**
- 7.5.1 总则：文件清单、文件结构
- 7.5.2 创建和更新：文件编制、审核、批准流程
- 7.5.3 文件化信息的控制：文件发放、回收、版本控制

### 第8章 运行

**8.1 运行策划和控制**
- 运行过程策划输出
- 过程控制准则
- 外包过程识别和控制

**8.2 应急准备和响应**
- 潜在紧急情况识别（火灾、爆炸、泄漏、自然灾害等）
- 应急预案清单
- 应急演练记录
- 应急设备清单
- 应急演练效果评价

### 第9章 绩效评价

**9.1.1 总则**
- 监视测量对象、方法、时机
- 环境绩效参数

**9.1.2 合规性评价**
- 合规性评价记录
- 合规义务履行情况
- 不符合项及整改

**9.2.1 总则**
- 内审方案和计划

**9.2.2 内部审核方案**
- 内审检查表
- 不符合项报告和分布
- 审核发现和结论

**9.3 管理评审**
- 管理评审计划
- 管理评审输入
- 管理评审输出
- 管理评审决议跟踪

### 第10章 改进

**10.1 总则**
- 改进机会识别
- 改进目标设定

**10.2 不符合和纠正措施**
- 不符合项描述
- 原因分析
- 纠正措施制定和实施
- 措施有效性验证

**10.3 持续改进**
- 持续改进项目清单
- 改进成果和效益

## 三、输出要求

1. 仅输出 JSON，不要有任何额外文字说明
2. 所有字段必须存在（不能省略），无法提取的字段设置为：字符串型填"未明确"或""，数组型填 []，对象型填 {}
3. 条款专项信息按以下格式组织：
```json
{
  "clauseDetails": {
    "4.1": { "applicable": true/false, "evidence": "证据描述", "extractedInfo": { ... } },
    "4.2": { "applicable": true/false, "evidence": "证据描述", "extractedInfo": { ... } },
    ...
  }
}
```
4. 对于不适用的条款，applicable 设为 false，evidence 和 extractedInfo 留空
5. 对于适用的条款，applicable 设为 true，evidence 描述文档中体现该条款要求的具体内容，extractedInfo 提取该条款要求的专项信息
6. 所有日期格式统一为 YYYY-MM-DD 或 YYYY-MM
7. 人员姓名、产品名称等实体名称必须与文档原文一致
8. 条款编号使用标准编号格式（如 4.1、6.1.2、7.4.3、8.2 等）

## 四、提取策略

1. 先通读全文，判断文档类型和涉及的主要环境管理过程
2. 提取通用字段（keyPersons、keyDates、keyProducts、keyMeasures、tableData）
3. 逐条款判断适用性，提取条款专项信息
4. 对于环境因素清单类文档，重点提取 6.1.2 的专项信息
5. 对于合规评价类文档，重点提取 9.1.2 的专项信息
6. 对于应急预案类文档，重点提取 8.2 的专项信息
7. 对于监测报告类文档，重点提取 9.1.1 的专项信息
8. 对于内审资料，重点提取 9.2 的专项信息
9. 对于管理评审资料，重点提取 9.3 的专项信息
10. 对于不符合项/纠正措施记录，重点提取 10.2 的专项信息'
WHERE Code = 'ISO14001-2016';

