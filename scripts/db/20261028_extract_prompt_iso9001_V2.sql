## 二、条款专项提取要求

根据文档内容判断涉及以下哪些条款，并提取对应专项信息。如果文档不涉及某条款，该条款对象为空对象 {}。

### 第4章 组织环境

**4.1 理解组织及其环境**
- 是否识别了内外部环境因素（PEST分析、SWOT分析等）
- 外部环境因素清单：政治、经济、社会、技术、竞争等方面的因素
- 内部环境因素清单：组织文化、资源能力、知识、管理体系等方面的因素
- 这些因素是否被监视和评审

**4.2 理解相关方的需求和期望**
- 是否识别了相关方（顾客、员工、供应商、股东、监管机构、社区等）
- 相关方需求和期望清单
- 这些需求是否被监视和评审

**4.3 确定质量管理体系的范围**
- 范围声明内容（产品、服务、过程、地点、排除项）
- 排除的条款编号及排除理由
- 排除是否不影响组织能力或责任

**4.4 质量管理体系及其过程**
- 过程识别清单（核心过程、支持过程、管理过程）
- 过程的输入、输出、顺序和相互作用
- 过程准则和绩效指标
- 过程资源分配

### 第5章 领导作用

**5.1 领导作用和承诺**
- 最高管理者参与证据（方针签署、管理评审主持、资源提供等）
- 质量管理体系有效性的承诺证据
- 以顾客为关注焦点的体现

**5.2 方针**
- 质量方针内容原文
- 方针是否与组织宗旨和战略方向一致
- 方针是否包含满足要求和持续改进的承诺
- 方针沟通证据

**5.3 组织的岗位、职责和权限**
- 组织架构图或职责分配描述
- 关键岗位的职责和权限定义
- 质量管理体系代表任命
- 过程责任分配

### 第6章 策划

**6.1 应对风险和机遇的措施**
- 风险识别清单（过程风险、产品风险、合规风险等）
- 风险评价准则和方法
- 风险应对措施（规避、降低、转移、接受）
- 机遇利用措施
- 风险与机遇的监视和评审机制

**6.2 质量目标及其实现的策划**
- 质量目标清单（公司级、部门级、过程级）
- 目标是否可测量、与方针一致
- 目标实现措施和责任人
- 目标完成情况的监视

**6.3 变更的策划**
- 变更管理程序或记录
- 变更评审、批准、实施流程
- 变更的风险评估和沟通

### 第7章 支持

**7.1 资源**
- 7.1.1 总则：资源配置原则和决策依据
- 7.1.2 人员：人员配置清单、岗位需求
- 7.1.3 基础设施：设备清单、厂房设施、IT系统、运输资源
- 7.1.4 过程运行环境：温度、湿度、洁净度、噪声、照明等环境因素控制
- 7.1.5 监视和测量资源：计量器具清单、校准计划、校准证书、测量溯源链
- 7.1.6 组织的知识：知识管理清单、技术资料、经验积累、学习机制

**7.2 能力**
- 岗位能力要求（教育、培训、技能、经验）
- 培训需求识别和培训计划
- 培训实施记录和效果评价
- 人员能力确认记录

**7.3 意识**
- 员工质量意识培训记录
- 方针和目标的理解证据
- 不符合项后果的认知

**7.4 沟通**
- 沟通管理程序
- 内部沟通（会议、通知、报告）
- 外部沟通（顾客、供应商、监管机构）
- 沟通内容和时机

**7.5 成文信息**
- 7.5.1 总则：文件清单、文件结构
- 7.5.2 创建和更新：文件编制、审核、批准流程
- 7.5.3 成文信息的控制：文件发放、回收、版本控制、文件标识、外来文件管理

### 第8章 运行

**8.1 运行的策划和控制**
- 运行过程策划输出（控制计划、工艺方案等）
- 过程控制准则
- 外包过程识别和控制

**8.2 产品和服务的要求**
- 8.2.1 顾客沟通：沟通渠道、沟通内容、顾客反馈处理
- 8.2.2 产品和服务要求的确定：顾客要求、法规要求、组织附加要求
- 8.2.3 产品和服务要求的评审：评审记录、能力确认、合同评审
- 8.2.4 产品和服务要求的更改：变更通知、重新评审

**8.3 产品和服务的设计和开发**
- 8.3.1 总则：设计开发流程、设计开发性质
- 8.3.2 设计和开发策划：阶段划分、评审验证确认安排、职责权限
- 8.3.3 设计和开发输入：功能性能要求、法规标准、以前设计信息、潜在失效模式
- 8.3.4 设计和开发控制：评审记录、验证记录、确认记录
- 8.3.5 设计和开发输出：图纸、规范、BOM、作业指导书
- 8.3.6 设计和开发更改：更改评审、批准、实施记录

**8.4 外部提供的过程、产品和服务的控制**
- 8.4.1 总则：外部提供类型、控制准则
- 8.4.2 控制类型和程度：供应商评价、选择、绩效监视
- 8.4.3 提供给外部供方的信息：采购规范、验收标准、价格交期

**8.5 生产和服务提供**
- 8.5.1 生产和服务提供的控制：作业指导书、工艺参数、设备维护、人员资格
- 8.5.2 标识和可追溯性：产品标识、状态标识、追溯记录
- 8.5.3 顾客或外部供方的财产：顾客财产识别、验证、保护
- 8.5.4 防护：搬运、包装、储存、防护措施
- 8.5.5 交付后活动：售后服务、技术支持、投诉处理
- 8.5.6 更改控制：生产变更评审、批准、实施

**8.6 产品和服务的放行**
- 检验计划和检验规范
- 进货检验、过程检验、成品检验记录
- 放行授权和记录
- 检验设备和方法

**8.7 不合格输出的控制**
- 不合格品识别和记录
- 不合格品评审和处置（返工、返修、让步接收、报废、退货）
- 纠正措施启动
- 顾客通知（如适用）

### 第9章 绩效评价

**9.1 监视、测量、分析和评价**
- 9.1.1 总则：监视测量对象、方法、时机
- 9.1.2 顾客满意：顾客满意度调查、反馈分析
- 9.1.3 分析与评价：质量目标达成、过程绩效、产品合格率、供应商绩效

**9.2 内部审核**
- 内审方案和计划
- 内审检查表
- 不符合项报告和分布
- 审核发现和结论
- 纠正措施跟踪

**9.3 管理评审**
- 管理评审计划
- 管理评审输入（审核结果、顾客反馈、过程绩效、不符合项、纠正措施、资源需求等）
- 管理评审输出（改进决策、资源需求、体系变更）
- 管理评审决议跟踪

### 第10章 改进

**10.1 总则**
- 改进机会识别
- 改进目标设定

**10.2 不合格和纠正措施**
- 不符合项描述
- 原因分析（5Why、鱼骨图等）
- 纠正措施制定和实施
- 措施有效性验证
- 文件更新（如需要）

**10.3 持续改进**
- 持续改进项目清单
- 改进方法和工具（PDCA、六西格玛、精益等）
- 改进成果和效益

## 三、输出要求

1. 仅输出 JSON，不要有任何额外文字说明
2. 所有字段必须存在（不能省略），无法提取的字段设置为：字符串型填"未明确"或""，数组型填 []，对象型填 {}
3. 条款专项信息按以下格式组织：
```json
{
  "clauseDetails": {
    "4.1": { "applicable": true/false, "evidence": "证据描述", "extractedInfo": { ... } },
    "4.2": { "applicable": true/false, "evidence": "证据描述", "extractedInfo": { ... } },
    ...
  }
}
```
4. 对于不适用的条款，applicable 设为 false，evidence 和 extractedInfo 留空
5. 对于适用的条款，applicable 设为 true，evidence 描述文档中体现该条款要求的具体内容，extractedInfo 提取该条款要求的专项信息
6. 所有日期格式统一为 YYYY-MM-DD 或 YYYY-MM
7. 人员姓名、产品名称等实体名称必须与文档原文一致
8. 条款编号使用标准编号格式（如 4.1、5.1.1、7.1.5.2、8.5.1 等）

## 四、提取策略

1. 先通读全文，判断文档类型和涉及的主要过程
2. 提取通用字段（keyPersons、keyDates、keyProducts、keyMeasures、tableData）
3. 逐条款判断适用性，提取条款专项信息
4. 对于表格类文档，重点提取 tableData 中的核心字段和值
5. 对于记录类文档，重点提取 keyDates 和 keyPersons
6. 对于程序文件，重点提取 clauseDetails 中的成文信息要求
7. 对于检验报告，重点提取 8.6 和 9.1 的专项信息
8. 对于内审资料，重点提取 9.2 的专项信息
9. 对于管理评审资料，重点提取 9.3 的专项信息
10. 对于不符合项/纠正措施记录，重点提取 10.2 的专项信息'
WHERE Code = 'ISO9001-2016';

