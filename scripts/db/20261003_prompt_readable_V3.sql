- ⛔ 不要输出 JSON Schema 本体、⛔ 不要输出「以下是提示词」之类的引导语'
 WHERE `PromptType` = 'prompt_generator'
   AND `IsDeleted` = 0;

-- ────────────────────────────────────────────────────────────
-- 验证
-- ────────────────────────────────────────────────────────────
SELECT `PromptCode`,
       `PromptType`,
       CHAR_LENGTH(`Template`)                                              AS 正文字数,
       LOCATE('{{standard_name}}', `Template`)   > 0                        AS 有标准名,
       LOCATE('{{std_doc_catalog}}', `Template`) > 0                        AS 有标准文档清单,
       LOCATE('{{folder_tree}}', `Template`)     > 0                        AS 有目录树,
       LOCATE('{{tag_list}}', `Template`)        > 0                        AS 有标签清单,
       LOCATE('{{output_schema}}', `Template`)   > 0                        AS 有输出契约,
       LOCATE('{{tag_constraint}}', `Template`)  > 0                        AS 有字典约束,
       -- ⚠️ 装饰符号检查只对**两类业务提示词**生效：
       --    元提示词必须**点名**「不要使用 ★、〇」才能约束模型，
       --    所以它的正文里必然出现这两个字符 —— 这是误报，故排除。
       CASE WHEN `PromptType` = 'prompt_generator' THEN NULL
            ELSE LOCATE('★', `Template`) = 0 END                             AS 无装饰星号,
       CASE WHEN `PromptType` = 'prompt_generator' THEN NULL
            ELSE LOCATE('〇、', `Template`) = 0 END                           AS 无圆圈序号,
       `ModelName` IS NULL AND `MaxTokens` IS NULL AND `Temperature` IS NULL AS 行级参数已停用
  FROM `wf_prompt_template`
 WHERE `IsDeleted` = 0
 ORDER BY `PromptType`;
-- 期望：
--   doc_group / doc_content → 8 个占位符检查全为 1（含 folder_tree）；
--                             无装饰星号 = 1、无圆圈序号 = 1
--   prompt_generator        → 有标准名 / 有标签清单 / 有输出契约 / 有字典约束 = 1；
--                             有标准文档清单 / 有目录树 = 0（元提示词不需要，正常）；
--                             无装饰星号 / 无圆圈序号 = NULL（不适用，见上）
--   三条都应为 行级参数已停用 = 1

-- ★ 残留占位符体检：正文里出现了不在白名单内的 {{xxx}} 即为「写了不会替换」的死占位符。
--   （PromptRenderer 未命中时保留原文 ⇒ 模型会看到无意义的字面量）
SELECT `PromptCode`,
       REGEXP_SUBSTR(`Template`, '\\{\\{[a-zA-Z_]+\\}\\}')  AS 首个花括号片段,
       (CHAR_LENGTH(`Template`) - CHAR_LENGTH(REPLACE(`Template`, '{{', ''))) / 2 AS 花括号对数
  FROM `wf_prompt_template`
 WHERE `IsDeleted` = 0
 ORDER BY `PromptType`;
