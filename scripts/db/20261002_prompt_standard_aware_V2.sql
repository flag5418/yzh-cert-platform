## 六、正文骨架（★ 必须分节成文，全文 ≥ 600 字）

一条合格的提示词正文至少包含下列 7 段，缺一段就不合格：

1. **角色与任务** —— 下游模型是谁、要完成什么
2. **当前服务的标准** —— 标准名 + 该标准要求的标准文档清单（★ 这一段是提示词按标准差异化的关键，必须写进去，不能只写「体系认证」四个字）
3. **输入说明** —— 下游会收到什么（字段名、粒度、是清单还是全文）
4. **判定规则** —— 标签怎么选、优先级、L0 确定性规则怎么用、什么情况降低置信度
5. **输出契约** —— 要哪些字段、每个字段什么含义、取值范围
6. **硬性约束** —— 禁止事项（禁止自造标签、禁止臆造字段、禁止输出解释文字等）
7. **标准差异提示** —— 明确告诉下游：不同标准下同一类文档的要求不同，判定必须结合本标准的文档清单

