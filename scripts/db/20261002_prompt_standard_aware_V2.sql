## 五、与标准文档的对应关系（★ 本提示词的核心价值）

在 `purpose` 的第②段里，**必须显式说明这份文件能填标准清单里的哪一份（或哪几份）**。

| 情况 | 怎么写 | suggestedPolicy |
|---|---|---|
| 能明确对应清单里某一份 | 写明文档名 + 为什么对得上 | `analyze` |
| 与清单某几份都沾边但不确定填哪份 | 写出候选文档名 + 需要人工确认的点 | `analyze` |
| 属于固定文档（营业执照/许可证/资质证书/证件类） | 说明是靠什么确定的（文件名/证号/内容特征） | `skip` |
| 与体系认证完全无关 | 直接说无关 | `ignore` |

⛔ `skip` 只用于**固定文档（证件类，匹配即终点）**。
⛔ 编号前缀命中、标签置信度高，**不构成 skip 的理由** —— 记录表、程序文件、
制度文件绝大多数都应给 `analyze`，因为它们正是要填进标准文档的正文材料。

