## 四、标签规则

- **一文档多标签，至少一个**：既给「形态」标签（记录表格/程序文件…），
  也给「业务过程」标签（内部审核/管理评审…），能确定时尽量给全
- 编号前缀或标题能直接判定 → `confidence` ≥ 0.9，`reason` 引用**命中的原文**
- 判标签时**优先看能否对应上面「标准文档清单」里的某一份** —— 能对应上的标签更有价值
- 无编号、片段信息不足 → 降低 `confidence`，`reason` 写清依据不足，标签仍从字典里选最接近的一个
- 彻底无法归类 → `tagCode` = `OTHER`

## 五、处理策略 suggestedPolicy（三选一，必须给）

⚠️ **这里的 skip 与「省一次 AI 调用」无关**，它是一个业务分流决定，判错会导致资料永远不进入填写环节。

| 值 | 判定条件 | 含义与后果 |
|---|---|---|
| `skip` | 该文件是**固定文档**（营业执照 / 生产许可证 / 资质证书 / 法人身份证 / 体系认证证书这类**证件类**，靠文件名或内容即可确定），或**其值已由企业在全局参数中直接给定** | 固定文档「匹配即终点」：**不再读全文**，也不进入后续定向提取与契约填充 |
| `ignore` | 与体系认证完全无关（个人材料、临时文件、乱码、无关截图等） | 丢弃，不进入任何后续流程 |
| `analyze` | **其余全部情况** | 需再读全文精判（含：所有 editable 记录/程序/制度类文件） |

⛔ **编号前缀命中、标签置信度高 ≠ skip**。标签判得准只说明「标签不用再猜」，
不说明「这份资料不需要读全文」——记录表、程序文件、制度文件绝大多数都应给 `analyze`。

`policyReason` 一句话说明为什么是这个策略。

## 六、硬性约束

{{tag_constraint}}

1. 清单里**每个文件都必须输出一条**，顺序与 `index` 一致，禁止遗漏、禁止合并、禁止编造清单外的文件
2. `reason` 必须引用**实际看到的**文件名 / 标题 / 片段原文，禁止写「推测」「可能是」
3. `purpose` ≤ 80 字，按「是什么 + 主要用途 + 能填标准清单里的哪一份」写；依据不足时写「依据不足，待全文精判」
4. 所有分数取值 0~1，保留两位小数
5. 只输出 JSON

