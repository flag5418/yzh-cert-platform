/**
 * 帮助浮层文案的**轻量富文本**分段（纯函数，可单测）。
 *
 * 【为什么需要它（2026-10-06 代码评审 #1）】
 *   Vue 的 `{{ }}` 插值**不解析 Markdown** —— 把 `'仅**可编辑文档**适用'` 直接塞进去，
 *   用户看到的是**字面的星号**。这个坑本页已经踩过两次：
 *     ① `PreviewPane.vue` 的脚注：`选择一个**文件**`；
 *     ② 帮助浮层（本次）。
 *
 *   `PreviewPane.vue` 当时留的口径是「需要强调就用静态文案 + 动态文案分开渲染，
 *   ⛔ 别在插值里写标记」。但帮助浮层是**静态配置表**（`HELP`，2 个 Tab × 4 条），
 *   每条都拆成多段会把配置表撑得没法读。
 *   ⇒ 改为**主动解析**：把标记拆成「纯文本段 / 加粗段」的数组，模板用
 *     `<strong>` 渲染 —— 既保留强调，又不泄漏标记，且**可单测**。
 *
 * 【语法】只认 `**x**`（不跨行、不允许嵌套）。其余一律原样，⛔ 不抛异常 ——
 *   文案写错最多是不加粗，⛔ 不该把整页打挂。
 */

/** 一个渲染片段：`b === true` 时用 `<strong>` 包起来 */
export interface RichSegment {
  /** 片段文本（已剥掉标记） */
  t: string
  /** 是否为加粗段 */
  b?: boolean
}

/**
 * 把带 `**加粗**` 的文案拆成片段数组。
 *
 * ⚠️ 用**捕获组**切分（`split` 带捕获组会把分隔符保留在结果里），
 *   否则标记本身会被吃掉、无法判断哪一段该加粗。
 * ⚠️ `[^*]+` 而非 `.+?`：`**` 内不允许再出现星号 ⇒ 天然挡住 `**a**b**` 这类歧义写法。
 */
export function parseBold(text: string): RichSegment[] {
  const s = String(text ?? '')
  if (!s.includes('**')) return s === '' ? [] : [{ t: s }]

  return s
    .split(/(\*\*[^*]+\*\*)/g)
    .filter((x) => x !== '')
    .map((x) =>
      x.length > 4 && x.startsWith('**') && x.endsWith('**')
        ? { t: x.slice(2, -2), b: true }
        : { t: x },
    )
}
