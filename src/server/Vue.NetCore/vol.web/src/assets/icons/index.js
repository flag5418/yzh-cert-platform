/**
 * 获取 Element Plus 图标组件
 * @param {string} iconName - 图标名称，如 'Plus', 'Search'
 * @returns {Component} 图标组件
 */
function getElementIcon(iconName) {
  return ElementPlusIconsVue[iconName] || null
}

/**
 * 获取 Bootstrap Icons 类名
 * @param {string} iconKey - 图标键名，如 'bi-plus-lg', 'bi-search'
 * @returns {string} 图标类名
 */
function getBootstrapIconClass(iconKey) {
  return iconKey.startsWith('bi-') ? iconKey : `bi-${iconKey}`
}

/**
 * YZH 图标工具类
 */
const YzhIcons = {
  /**
   * 获取 Element Plus 图标组件
   */
  getElIcon: getElementIcon,
  
  /**
   * 获取 Bootstrap Icons 类名
   */
  getBootstrapIcon: getBootstrapIconClass,
  
  /**
   * 检查图标是否存在
   */
  hasIcon: (iconName) => {
    return !!getElementIcon(iconName) || !!iconName.startsWith('bi-')
  },
  
  /**
   * 获取所有 Element Plus 图标名称
   */
  getAllElIconNames: () => {
    return Object.keys(ElementPlusIconsVue)
  },
  
  /**
   * 获取所有 Bootstrap Icons 键名
   */
  getAllBootstrapIconKeys: () => {
    return Object.keys(bootstrapIcons)
  }
}

export default YzhIcons
export { getElementIcon, getBootstrapIconClass, bootstrapIcons }
