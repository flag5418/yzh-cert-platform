def md5(s: str) -> str:
    return hashlib.md5(s.encode("utf-8")).hexdigest()


def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace("'", "''")


def validate(clauses, key):
    nums = [c[0] for c in clauses]
    assert len(nums) == len(set(nums)), f"{key} 条款编号重复"
    for num, title in clauses:
        assert title.strip(), f"{key} {num} 标题为空"
        if "." in num:
            parent = num.rsplit(".", 1)[0]
            assert parent in nums, f"{key} {num} 的父条款 {parent} 不在清单中"


